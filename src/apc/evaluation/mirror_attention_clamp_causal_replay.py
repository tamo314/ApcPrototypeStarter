        current_model.cross_attn.in_proj_weight.data[: 2 * embed_dim].copy_(frozen_qkv_weight)
        if current_model.cross_attn.in_proj_bias is not None and frozen_qkv_bias is not None:
            current_model.cross_attn.in_proj_bias.data[: 2 * embed_dim].copy_(frozen_qkv_bias)

        current_opt_w = optimizer.state[current_model.cross_attn.in_proj_weight]
        current_opt_w["exp_avg"][: 2 * embed_dim].copy_(frozen_exp_avg_w)
        current_opt_w["exp_avg_sq"][: 2 * embed_dim].copy_(frozen_exp_avg_sq_w)

        if (
            current_model.cross_attn.in_proj_bias is not None
            and frozen_exp_avg_b is not None
            and frozen_exp_avg_sq_b is not None
        ):
            current_opt_b = optimizer.state[current_model.cross_attn.in_proj_bias]
            current_opt_b["exp_avg"][: 2 * embed_dim].copy_(frozen_exp_avg_b)
            current_opt_b["exp_avg_sq"][: 2 * embed_dim].copy_(frozen_exp_avg_sq_b)

