def verify_attention_clamp_initial_parity(
    core: Any,
    primitive_7500: CrossPositionLengthBiasPrimitive,
    reference_7500: CrossPositionLengthBiasPrimitive,
    examples: list[Example],
) -> dict[str, Any]:
    """Confirms that at step 7500, normal forward and clamped forward match within tolerance."""
    primitive_7500.eval()
    reference_7500.eval()
    device = core.device

    batch_exs = examples[:64]
    batch_input = collate_content_only_batch(batch_exs, core.tokens, device=device)
    with torch.no_grad():
        h = core.model.encode(batch_input)[:, 1:11, :]
        c_lens = [len(ex.input_tokens) for ex in batch_exs]
        o_lens = [10] * len(batch_exs)

        # 1. Normal forward
        normal_out = rec004t.evaluate_forward_with_stages(
            primitive_7500, h, c_lens, o_lens, oracle_attention=False
        )
        normal_attn = normal_out["attn_probs"]
        normal_logits = normal_out["final_token_logits"]
        normal_preds = normal_logits.argmax(dim=-1)

        # 2. Clamped forward with A_ref
        a_ref = extract_reference_attention(reference_7500, h, c_lens, o_lens)
        clamped_out = clamped_forward_with_stages(primitive_7500, h, c_lens, o_lens, a_ref)
        clamped_logits = clamped_out["final_token_logits"]
        clamped_preds = clamped_logits.argmax(dim=-1)

        # Comparisons
        attn_max_abs_diff = float(torch.max(torch.abs(normal_attn - a_ref)).item())
        logits_max_abs_diff = float(torch.max(torch.abs(normal_logits - clamped_logits)).item())
        preds_exact_match = bool(torch.all(normal_preds == clamped_preds).item())

    # Pre-declared tolerances
    attn_passed = attn_max_abs_diff < REC004U_INITIAL_PARITY_ATTN_TOLERANCE
    logits_passed = logits_max_abs_diff < REC004U_INITIAL_PARITY_LOGITS_TOLERANCE
    status_pass = attn_passed and logits_passed and preds_exact_match

    parity_result = {
        "task_id": REC004U_TASK_ID,
        "step": REC004U_START_STEP,
        "n_verified_examples": len(batch_exs),
        "attn_max_abs_diff": attn_max_abs_diff,
        "attn_tolerance": REC004U_INITIAL_PARITY_ATTN_TOLERANCE,
        "attn_passed": attn_passed,
        "logits_max_abs_diff": logits_max_abs_diff,
        "logits_tolerance": REC004U_INITIAL_PARITY_LOGITS_TOLERANCE,
        "logits_passed": logits_passed,
        "preds_exact_match": preds_exact_match,
        "bitwise_exact": (attn_max_abs_diff == 0.0 and logits_max_abs_diff == 0.0),
        "status": "PASS" if status_pass else "FAIL",
    }

    if not status_pass:
        raise RuntimeError(
            f"ATTENTION_CLAMP_INITIAL_PARITY_FAILURE: Parity gate failed at step 7500! "
            f"attn_diff={attn_max_abs_diff}, logits_diff={logits_max_abs_diff}, "
            f"preds_match={preds_exact_match}"
        )

    return parity_result


