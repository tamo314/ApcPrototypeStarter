def evaluate_dataset_triplet_metrics(
    core: Any,
    current_primitive: CrossPositionLengthBiasPrimitive,
    reference_primitive: CrossPositionLengthBiasPrimitive,
    examples: list[Example],
    batch_size: int = 128,
) -> dict[str, Any]:
    """Evaluates normal J0, oracle O1, and clamped forward, plus attention drift vs A_ref."""
    current_primitive.eval()
    reference_primitive.eval()
    device = core.device
    n_total = len(examples)

    # Counts
    j0_seq_matches = 0
    o1_seq_matches = 0
    clamped_seq_matches = 0

    j0_p4_matches = 0
    j0_p5_matches = 0
    o1_p4_matches = 0
    o1_p5_matches = 0
    clamped_p4_matches = 0
    clamped_p5_matches = 0

    # Margins
    o1_p4_logit_margins: list[float] = []
    o1_p5_logit_margins: list[float] = []

    # Attention Drift Metrics (Current normal J0 attention vs A_ref)
    kl_divergences: list[float] = []
    kl_p4_list: list[float] = []
    kl_p5_list: list[float] = []
    delta_p_correct_p4_list: list[float] = []
    delta_p_correct_p5_list: list[float] = []
    argmax_disagree_p4_count = 0
    argmax_disagree_p5_count = 0
    argmax_disagree_total_slots = 0
    argmax_disagree_all_count = 0

    with torch.no_grad():
        for start_idx in range(0, n_total, batch_size):
            chunk = examples[start_idx : start_idx + batch_size]
            b_size = len(chunk)
            batch_input = collate_content_only_batch(chunk, core.tokens, device=device)
            h = core.model.encode(batch_input)[:, 1:11, :]
            c_lens = [len(ex.input_tokens) for ex in chunk]
            o_lens = [10] * b_size

            target_tokens = torch.tensor(
                [ex.target_tokens for ex in chunk], device=device, dtype=torch.long
            )

            # 1. Reference attention
            a_ref = extract_reference_attention(reference_primitive, h, c_lens, o_lens)

            # 2. Normal J0
            j0_out = rec004t.evaluate_forward_with_stages(
                current_primitive, h, c_lens, o_lens, oracle_attention=False
            )
            j0_logits = j0_out["final_token_logits"]
            j0_preds = torch.argmax(j0_logits, dim=-1)
            j0_attn = j0_out["attn_probs"]  # [B, H, 10, 10]

            # 3. Oracle O1
            o1_out = rec004t.evaluate_forward_with_stages(
                current_primitive, h, c_lens, o_lens, oracle_attention=True
            )
            o1_logits = o1_out["final_token_logits"]
            o1_preds = torch.argmax(o1_logits, dim=-1)

            # 4. Clamped forward
            clamped_out = clamped_forward_with_stages(current_primitive, h, c_lens, o_lens, a_ref)
            clamped_logits = clamped_out["final_token_logits"]
            clamped_preds = torch.argmax(clamped_logits, dim=-1)

            # Sequence matches
            j0_seq_matches += int(torch.all(j0_preds == target_tokens, dim=-1).sum().item())
            o1_seq_matches += int(torch.all(o1_preds == target_tokens, dim=-1).sum().item())
            clamped_seq_matches += int(
                torch.all(clamped_preds == target_tokens, dim=-1).sum().item()
            )

            # Position 4 & 5 matches
            j0_p4_matches += int(
                (j0_preds[:, REC004U_POSITION_4] == target_tokens[:, REC004U_POSITION_4])
                .sum()
                .item()
            )
            j0_p5_matches += int(
                (j0_preds[:, REC004U_POSITION_5] == target_tokens[:, REC004U_POSITION_5])
                .sum()
                .item()
            )
            o1_p4_matches += int(
                (o1_preds[:, REC004U_POSITION_4] == target_tokens[:, REC004U_POSITION_4])
                .sum()
                .item()
            )
            o1_p5_matches += int(
                (o1_preds[:, REC004U_POSITION_5] == target_tokens[:, REC004U_POSITION_5])
                .sum()
                .item()
            )
            clamped_p4_matches += int(
                (clamped_preds[:, REC004U_POSITION_4] == target_tokens[:, REC004U_POSITION_4])
                .sum()
                .item()
            )
            clamped_p5_matches += int(
                (clamped_preds[:, REC004U_POSITION_5] == target_tokens[:, REC004U_POSITION_5])
                .sum()
                .item()
            )

            # O1 logit margins
            for b in range(b_size):
                y_p4 = target_tokens[b, REC004U_POSITION_4].item()
                y_p5 = target_tokens[b, REC004U_POSITION_5].item()

                p4_o1_l = o1_logits[b, REC004U_POSITION_4, :]
                p4_o1_w = p4_o1_l.clone()
                p4_o1_w[y_p4] = -torch.inf
                o1_p4_logit_margins.append(float((p4_o1_l[y_p4] - torch.max(p4_o1_w)).item()))

                p5_o1_l = o1_logits[b, REC004U_POSITION_5, :]
                p5_o1_w = p5_o1_l.clone()
                p5_o1_w[y_p5] = -torch.inf
                o1_p5_logit_margins.append(float((p5_o1_l[y_p5] - torch.max(p5_o1_w)).item()))

            # Attention Drift Metrics
            # j0_attn vs a_ref: shape [B, H, 10, 10]
            eps = 1e-12
            kl_tensor = a_ref * (torch.log(a_ref + eps) - torch.log(j0_attn + eps))
            kl_per_pos = kl_tensor.sum(dim=-1).mean(dim=1)  # [B, 10]

            kl_divergences.extend(kl_per_pos.mean(dim=-1).cpu().tolist())
            kl_p4_list.extend(kl_per_pos[:, REC004U_POSITION_4].cpu().tolist())
            kl_p5_list.extend(kl_per_pos[:, REC004U_POSITION_5].cpu().tolist())

            # Correct key delta
            # Head-averaged prob for correct key
            j0_p4_prob = j0_attn[:, :, REC004U_POSITION_4, REC004U_CORRECT_KEY_P4].mean(dim=1)
            ref_p4_prob = a_ref[:, :, REC004U_POSITION_4, REC004U_CORRECT_KEY_P4].mean(dim=1)
            delta_p_correct_p4_list.extend((j0_p4_prob - ref_p4_prob).cpu().tolist())

            j0_p5_prob = j0_attn[:, :, REC004U_POSITION_5, REC004U_CORRECT_KEY_P5].mean(dim=1)
            ref_p5_prob = a_ref[:, :, REC004U_POSITION_5, REC004U_CORRECT_KEY_P5].mean(dim=1)
            delta_p_correct_p5_list.extend((j0_p5_prob - ref_p5_prob).cpu().tolist())

            # Argmax disagreement (head-averaged or per-head?)
            # Across heads mean attention:
            j0_mean_attn = j0_attn.mean(dim=1)  # [B, 10, 10]
            ref_mean_attn = a_ref.mean(dim=1)  # [B, 10, 10]
            j0_argmax = j0_mean_attn.argmax(dim=-1)  # [B, 10]
            ref_argmax = ref_mean_attn.argmax(dim=-1)  # [B, 10]

            disagree_mask = j0_argmax != ref_argmax  # [B, 10]
            argmax_disagree_p4_count += int(disagree_mask[:, REC004U_POSITION_4].sum().item())
            argmax_disagree_p5_count += int(disagree_mask[:, REC004U_POSITION_5].sum().item())
            argmax_disagree_all_count += int(disagree_mask.sum().item())
            argmax_disagree_total_slots += b_size * 10

    return {
        "n_examples": n_total,
        # Normal J0
        "j0_sequence_em": j0_seq_matches / n_total,
        "j0_position4_acc": j0_p4_matches / n_total,
        "j0_position5_acc": j0_p5_matches / n_total,
        # Oracle O1
        "o1_sequence_em": o1_seq_matches / n_total,
        "o1_position4_acc": o1_p4_matches / n_total,
        "o1_position5_acc": o1_p5_matches / n_total,
        "o1_p4_logit_margin_median": float(np.median(o1_p4_logit_margins)),
        "o1_p5_logit_margin_median": float(np.median(o1_p5_logit_margins)),
        # Clamped forward
        "clamped_sequence_em": clamped_seq_matches / n_total,
        "clamped_position4_acc": clamped_p4_matches / n_total,
        "clamped_position5_acc": clamped_p5_matches / n_total,
        # Attention Drift vs A_ref
        "attn_drift_kl_mean": float(np.mean(kl_divergences)),
        "attn_drift_kl_p4_mean": float(np.mean(kl_p4_list)),
        "attn_drift_kl_p5_mean": float(np.mean(kl_p5_list)),
        "delta_p_correct_p4_mean": float(np.mean(delta_p_correct_p4_list)),
        "delta_p_correct_p5_mean": float(np.mean(delta_p_correct_p5_list)),
        "argmax_disagreement_rate_p4": argmax_disagree_p4_count / n_total,
        "argmax_disagreement_rate_p5": argmax_disagree_p5_count / n_total,
        "argmax_disagreement_rate_overall": (
            argmax_disagree_all_count / argmax_disagree_total_slots
            if argmax_disagree_total_slots > 0
            else 0.0
        ),
    }


