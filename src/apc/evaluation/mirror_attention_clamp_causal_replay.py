def extract_reference_attention(
    reference_primitive: CrossPositionLengthBiasPrimitive,
    content_features: torch.Tensor,
    content_lengths: list[int],
    output_lengths: list[int],
) -> torch.Tensor:
    """Computes normal J0 attention probabilities A_ref(x) from REFERENCE_7500.

    Information Boundary:
    Uses ONLY content features, content lengths, output lengths, and reference weights.
    Zero access to target tokens, oracle pi_n, teacher outputs, or validation correctness.
    Returns detached tensor with shape [batch, n_head, out_max, lmax].
    """
    with torch.no_grad():
        device = content_features.device
        batch, lmax, _ = content_features.shape
        out_max = max(output_lengths)

        # 1. Input preparation using REFERENCE_7500
        content_position_ids = torch.arange(lmax, device=device).unsqueeze(0).expand(batch, lmax)
        kv = reference_primitive.content_in_proj(
            content_features
        ) + reference_primitive.content_position_embedding(content_position_ids)

        query_ids = torch.arange(out_max, device=device).unsqueeze(0).expand(batch, out_max)
        query = reference_primitive.answer_query_embedding(query_ids)

        # 2. Q and K projection from REFERENCE_7500
        mha = reference_primitive.cross_attn
        embed_dim = reference_primitive.d_operator
        n_head = reference_primitive.n_head
        head_dim = embed_dim // n_head
        scale = 1.0 / math.sqrt(head_dim)

        wq, wk, _ = mha.in_proj_weight.chunk(3, dim=0)
        bq = bk = None
        if mha.in_proj_bias is not None:
            bq, bk, _ = mha.in_proj_bias.chunk(3, dim=0)

        q = F.linear(query, wq, bq)
        k = F.linear(kv, wk, bk)

        q = q.view(batch, out_max, n_head, head_dim).transpose(1, 2)
        k = k.view(batch, lmax, n_head, head_dim).transpose(1, 2)

        # Raw score logits before bias and mask
        s_other = torch.matmul(q, k.transpose(-2, -1)) * scale  # [batch, n_head, out_max, lmax]

        # Bias and mask from REFERENCE_7500
        bias = reference_primitive._position_bias(content_lengths, out_max, lmax, device)
        bias_expanded = bias.unsqueeze(1).expand(batch, n_head, out_max, lmax)

        content_lengths_t = torch.tensor(content_lengths, device=device).view(batch, 1, 1)
        p_idx_long = torch.arange(lmax, device=device).view(1, 1, lmax)
        pad_mask = (
            (p_idx_long >= content_lengths_t).unsqueeze(1).expand(batch, n_head, out_max, lmax)
        )

        raw_scores = s_other + bias_expanded
        scores = torch.where(pad_mask, torch.tensor(float("-inf"), device=device), raw_scores)

        attn_probs = F.softmax(scores, dim=-1)
        return attn_probs.detach()


def clamped_forward_with_stages(
    primitive: CrossPositionLengthBiasPrimitive,
    content_features: torch.Tensor,
    content_lengths: list[int],
    output_lengths: list[int],
    attn_probs: torch.Tensor,
) -> dict[str, Any]:
    """Runs forward pass where attention distribution is clamped to external attn_probs.

    Uses current model's own:
    - content_in_proj & content_position_embedding (CONTENT_PREP)
    - answer_query_embedding (QUERY_RESIDUAL)
    - V projection (V rows)
    - out_proj (ATTN_OUT_PROJ)
    - attn_norm (POST_ATTN_NORM)
    - ffn & ffn_norm (FFN)
    - readout (READOUT)

    Q, K, and position_bias are NOT evaluated or used.
    Zero access to target tokens or oracle metadata.
    """
    device = content_features.device
    batch, lmax, _ = content_features.shape
    out_max = max(output_lengths)

    # 1. Content prep (current model)
    content_position_ids = torch.arange(lmax, device=device).unsqueeze(0).expand(batch, lmax)
    kv = primitive.content_in_proj(content_features) + primitive.content_position_embedding(
        content_position_ids
    )

    query_ids = torch.arange(out_max, device=device).unsqueeze(0).expand(batch, out_max)
    query = primitive.answer_query_embedding(query_ids)

    # 2. V projection (current model)
    mha = primitive.cross_attn
    embed_dim = primitive.d_operator
    n_head = primitive.n_head
    head_dim = embed_dim // n_head

    # Extract V slice (rows 2*embed_dim : 3*embed_dim)
    wv = mha.in_proj_weight[2 * embed_dim : 3 * embed_dim, :]
    bv = mha.in_proj_bias[2 * embed_dim : 3 * embed_dim] if mha.in_proj_bias is not None else None

    v = F.linear(kv, wv, bv)
    v = v.view(batch, lmax, n_head, head_dim).transpose(1, 2)

    # 3. Clamped attention output
    # attn_probs: [batch, n_head, out_max, lmax]
    # v: [batch, n_head, lmax, head_dim]
    attn_out_heads = torch.matmul(attn_probs, v)  # [batch, n_head, out_max, head_dim]
    attn_out_concat = attn_out_heads.transpose(1, 2).reshape(batch, out_max, embed_dim)
    attn_out = mha.out_proj(attn_out_concat)

    # 4. Post-attention stages
    post_attn_res_in = query + attn_out
    post_attn_norm_out = primitive.attn_norm(post_attn_res_in)

    ffn_out = primitive.ffn(post_attn_norm_out)
    post_ffn_rep = primitive.ffn_norm(post_attn_norm_out + ffn_out)

    final_token_logits = primitive.readout(post_ffn_rep)

    return {
        "final_token_logits": final_token_logits,
        "attn_probs": attn_probs,
        "attn_out": attn_out,
        "post_attn_res_in": post_attn_res_in,
        "post_attn_norm_out": post_attn_norm_out,
        "ffn_out": ffn_out,
        "post_ffn_rep": post_ffn_rep,
    }


